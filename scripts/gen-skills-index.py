"""Regenerate docs/agent/SKILLS_INDEX.md from .claude/skills and .agents/skills.
Usage: python scripts/gen-skills-index.py
"""
import os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCES = ['.claude/skills', '.agents/skills']
GROUPS = [
    ('Sebooth core workflow (pakai ini dulu)', r'^(ponytail.*|karpathy-guidelines|surgical-patch|lean-build|investigate-first|verify-and-stop|safe-refactor|systematic-debugging|diagnosing-bugs|debugging-and-error-recovery|verification-before-completion)$'),
    ('Token saving (caveman)', r'^cave'),
    ('Planning & spec', r'(plan|spec|brainstorm|idea|grill|interview|wizard|implement|handoff|ask-matt|doubt|constraint)'),
    ('Code quality & review', r'(review|simplif|refactor|codebase|architecture|domain|api-and|deprecation|migrat|tdd|test|shoehorn|quality)'),
    ('Frontend & design', r'(design|ui|frontend|brand|banner|taste|image|css|visual|theme|canvas|art|gif|web-artifacts)'),
    ('Git, CI & shipping', r'(git|ci-cd|shipping|finishing|pre-commit|worktree|pr$)'),
    ('Agents & skills meta', r'(agent|skill|superpowers|context|prompt|subagent|dispatching|writing|discernment|full-output)'),
    ('Documents & office', r'(docx|pdf|pptx|xlsx|doc-|documentation|internal-comms)'),
]

def first_sentence(s, n=150):
    s = re.split(r'(?<=[.!?])\s', s, 1)[0]
    return s if len(s) <= n else s[:n - 1].rstrip() + '…'

skills = {}
for base in SOURCES:
    full = os.path.join(ROOT, base)
    for d in sorted(os.listdir(full)):
        p = os.path.join(full, d, 'SKILL.md')
        if d in skills or not os.path.exists(p):
            continue
        t = open(p, encoding='utf-8', errors='ignore').read()
        m = re.search(r'^description:\s*(.*?)(?=^\w[\w-]*:|^---)', t, re.S | re.M)
        desc = ' '.join((m.group(1) if m else '').split()).strip('"\'>|- ')
        skills[d] = (base, first_sentence(desc))

grouped = {g: [] for g, _ in GROUPS}
grouped['Other'] = []
for name in sorted(skills):
    g = next((g for g, rx in GROUPS if re.search(rx, name)), 'Other')
    grouped[g].append(name)

out = ['# Skills Index', '',
       f'{len(skills)} skills. Generated by `python scripts/gen-skills-index.py` — do not edit by hand.',
       'Source: `.claude/skills/` (Claude Code). `*` = only in `.agents/skills/` (Antigravity/other agents).', '']
for g, names in grouped.items():
    if not names:
        continue
    out += [f'## {g}', '']
    for n in names:
        base, desc = skills[n]
        star = '*' if base.startswith('.agents') else ''
        out.append(f'- **{n}**{star} — {desc}')
    out.append('')
path = os.path.join(ROOT, 'docs/agent/SKILLS_INDEX.md')
open(path, 'w', encoding='utf-8').write('\n'.join(out))
print(f'wrote {path} ({len(skills)} skills)')
